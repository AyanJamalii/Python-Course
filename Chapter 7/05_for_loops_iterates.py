# for loop with lists. 

list = [1, 3, 5, 6, 32, 22, 18]

for i in list:
    print(f"This is List: {i}")


# for loop in Tuples:

tuples = (2, 51, 51, 51, 25,)
for i in tuples:
    print(f"This is Tuples: {i}")

# For Loop In Strings: 

string = "Ayan"
for i in string:
    print(f"This is Strings: {i}")